#!/usr/bin/env node
import { execFile } from "node:child_process";
import { readFile, writeFile } from "node:fs/promises";
import { join } from "node:path";
import { promisify } from "node:util";

/**
 * Generates docs/cli.md by asking the built CLI for its own help.
 *
 * The source of truth is the binary, not a hand-written page: a reference that
 * is transcribed by hand is wrong within a month, and nobody notices until a
 * user follows it. `--check` re-generates into memory and fails if the result
 * differs from what is committed, which is what CI runs.
 *
 * Usage:
 *   node scripts/generate-cli-docs.mjs           # write docs/cli.md
 *   node scripts/generate-cli-docs.mjs --check   # fail if it would change
 */

const run = promisify(execFile);

const CLI = join(process.cwd(), "dist", "cli", "index.js");
const TARGET = join(process.cwd(), "docs", "cli.md");
const COMMANDS = ["search", "describe", "call", "replay", "inspect", "history", "env"];

async function help(args) {
  const { stdout } = await run(process.execPath, [CLI, ...args]);
  return stdout.trimEnd();
}

async function generate() {
  const sections = [
    "<!-- Generated by scripts/generate-cli-docs.mjs. Do not edit by hand. -->",
    "",
    "# CLI reference",
    "",
    "Every command accepts `--json` for machine-readable output. Errors go to",
    "stderr and set a non-zero exit code; with `--json` they are emitted as a",
    "JSON object with `code`, `message` and `hint`.",
    "",
    "## api-pilot",
    "",
    "```",
    await help(["--help"]),
    "```",
  ];

  for (const command of COMMANDS) {
    sections.push("", `## api-pilot ${command}`, "", "```", await help([command, "--help"]), "```");
  }

  return `${sections.join("\n")}\n`;
}

const generated = await generate();

if (process.argv.includes("--check")) {
  const current = await readFile(TARGET, "utf8").catch(() => "");
  if (current !== generated) {
    process.stderr.write(
      `docs/cli.md is out of date.\nRun \`pnpm run docs\` and commit the result.\n`,
    );
    process.exit(1);
  }
  process.stdout.write("docs/cli.md is up to date.\n");
} else {
  await writeFile(TARGET, generated, "utf8");
  process.stdout.write(`Wrote ${TARGET}\n`);
}
